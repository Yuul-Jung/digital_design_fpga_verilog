s=S(1000,420,'mealy_serial_frame_fsm 상태도','입력 w와 출력 y1y2를 w/y1y2로 표기한 Mealy 상태도. S0, S1, S2, S3, S4 상태와 전이')
P={'S0':(150,210),'S1':(420,110),'S2':(720,110),'S3':(420,310),'S4':(720,310)}; r=45
for k,(x,y) in P.items(): s.circle(x,y,r,k)
def edge(a,b,lbl,off):
    (x1,y1),(x2,y2)=P[a],P[b]; d=math.hypot(x2-x1,y2-y1); ux,uy=(x2-x1)/d,(y2-y1)/d
    s.poly([(round(x1+ux*r,1),round(y1+uy*r,1)),(round(x2-ux*r,1),round(y2-uy*r,1))])
    mx,my=(x1+x2)/2,(y1+y2)/2; s.lab(mx+off[0],my+off[1],lbl)
edge('S0','S1','1/10',(-14,-14)); edge('S1','S2','1/10',(0,-10)); edge('S3','S4','0/00',(0,-10))
